export const getAttractionById = (id) => {
  for (const country of destinationCountries) {
    const attraction = country.attractions.find((item) => item.id === id);
    if (attraction) {
      return { ...attraction, countryName: country.name, countryFlag: country.flag };
    }
  }
  return null;
};

export const getSimilarAttractions = (currentAttraction) => {
  if (!currentAttraction) return [];
  const sameCountry = [];
  const sameCategory = [];
  const nearby = [];

  destinationCountries.forEach((country) => {
    country.attractions.forEach((attraction) => {
      if (attraction.id === currentAttraction.id) return;
      if (attraction.country === currentAttraction.country) {
        sameCountry.push(attraction);
      } else if (attraction.category === currentAttraction.category) {
        sameCategory.push(attraction);
      } else {
        nearby.push(attraction);
      }
    });
  });

  return [...sameCountry, ...sameCategory, ...nearby].slice(0, 4);
};

export const getCountryById = (id) => destinationCountries.find((country) => country.id === id) || null;

export const searchAttractions = (query) => {
  if (!query || query.trim().length < 2) return [];
  const q = query.toLowerCase().trim();

  const results = [];
  destinationCountries.forEach((country) => {
    country.attractions.forEach((attraction) => {
      const searchable = [
        attraction.name,
        attraction.city,
        attraction.country,
        attraction.category,
        ...(attraction.tags || []),
      ].join(' ').toLowerCase();

      if (searchable.includes(q)) {
        results.push({
          ...attraction,
          countryName: country.name,
          countryFlag: country.flag,
        });
      }
    });
  });

  return results.slice(0, 8);
};
